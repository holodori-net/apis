import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

import ts from "typescript";

const projectRoot = path.resolve(import.meta.dirname, "..");
const servicesDirectory = path.join(projectRoot, "src/services");
const outputPath = path.join(projectRoot, "docs/api-reference.md");

const serviceFiles = (await readdir(servicesDirectory))
  .filter((file) => file.endsWith(".ts"))
  .sort();
const services = [];

for (const file of serviceFiles) {
  const sourceText = await readFile(path.join(servicesDirectory, file), "utf8");
  const source = ts.createSourceFile(
    file,
    sourceText,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  );
  for (const statement of source.statements) {
    if (!ts.isClassDeclaration(statement) || !statement.name) continue;
    if (!hasModifier(statement, ts.SyntaxKind.ExportKeyword)) continue;
    const classDoc = readDocumentation(statement);
    if (!classDoc.summary) {
      throw new Error(`${file}:${statement.name.text} has no JSDoc summary`);
    }

    const methodsByName = new Map();
    for (const member of statement.members) {
      if (!ts.isMethodDeclaration(member) || !member.name) continue;
      if (hasModifier(member, ts.SyntaxKind.PrivateKeyword)) continue;
      const name = member.name.getText(source);
      const entries = methodsByName.get(name) ?? [];
      entries.push(member);
      methodsByName.set(name, entries);
    }

    const methods = [];
    for (const [name, declarations] of methodsByName) {
      const documented = declarations.find(
        (declaration) => readDocumentation(declaration).summary.length > 0,
      );
      const doc = readDocumentation(documented ?? declarations[0]);
      if (!doc.summary) {
        throw new Error(
          `${file}:${statement.name.text}.${name} has no JSDoc summary`,
        );
      }
      const overloads = declarations.filter((declaration) => !declaration.body);
      const signatures = (overloads.length > 0 ? overloads : declarations).map(
        (declaration) => formatSignature(declaration, source),
      );
      methods.push({ name, ...doc, signatures });
    }
    services.push({ name: statement.name.text, ...classDoc, methods });
  }
}

const rendered = renderReference(services);
if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== rendered) {
    process.stderr.write(
      "docs/api-reference.md is stale; run `pnpm docs:api`.\n",
    );
    process.exitCode = 1;
  }
} else {
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, rendered);
}

function hasModifier(node, kind) {
  return node.modifiers?.some((modifier) => modifier.kind === kind) ?? false;
}

function readDocumentation(node) {
  if (!node) return { summary: "", remarks: "", rpc: "" };
  const block = node.jsDoc?.at(-1);
  const tags = block?.tags ?? [];
  return {
    summary: normalizeComment(block?.comment),
    remarks: normalizeComment(
      tags.find((tag) => tag.tagName.text === "remarks")?.comment,
    ),
    rpc: normalizeComment(
      tags.find((tag) => tag.tagName.text === "rpc")?.comment,
    ),
  };
}

function normalizeComment(comment) {
  if (typeof comment === "string") return comment.trim();
  if (!comment) return "";
  return comment
    .map((part) => part.text)
    .join("")
    .trim();
}

function formatSignature(method, source) {
  const typeParameters = method.typeParameters?.length
    ? `<${method.typeParameters.map((item) => item.getText(source)).join(", ")}>`
    : "";
  const parameters = method.parameters
    .map((parameter) => formatParameter(parameter, source))
    .join(", ");
  const returnType = method.type?.getText(source).replaceAll(/\s+/g, " ");
  return `${method.name.getText(source)}${typeParameters}(${parameters})${returnType ? `: ${returnType}` : ""}`;
}

function formatParameter(parameter, source) {
  const rest = parameter.dotDotDotToken ? "..." : "";
  const name = parameter.name.getText(source);
  const optional = parameter.questionToken || parameter.initializer ? "?" : "";
  const rawType = parameter.type?.getText(source).replaceAll(/\s+/g, " ");
  const normalizedType =
    optional && rawType ? rawType.replace(/\s*\|\s*undefined$/, "") : rawType;
  const type = normalizedType ? `: ${normalizedType}` : "";
  return `${rest}${name}${optional}${type}`;
}

function renderReference(items) {
  const lines = [
    "# API reference",
    "",
    "<!-- Generated by scripts/generate-api-docs.mjs. Do not edit directly. -->",
    "",
    "This reference describes the high-level methods currently implemented by `@holodori/apis`. See the [README](../README.md#recovered-api-catalog) for recovered methods that are not implemented yet.",
    "",
  ];
  for (const service of items.sort((left, right) =>
    left.name.localeCompare(right.name),
  )) {
    lines.push(`## ${service.name}`, "", service.summary, "");
    if (service.remarks) lines.push(service.remarks, "");
    for (const method of service.methods) {
      lines.push(`### \`${method.name}()\``, "", method.summary, "");
      if (method.rpc) lines.push(`RPC: \`${method.rpc}\``, "");
      if (method.remarks) lines.push(method.remarks, "");
      lines.push("```ts", ...method.signatures, "```", "");
    }
  }
  return `${lines.join("\n").trim()}\n`;
}
